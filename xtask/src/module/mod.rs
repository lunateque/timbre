//! `cargo xtask module new|remove`: the only way a module enters or leaves the tree.
//!
//! Every manifest edit is computed over file text before anything is written, so a
//! missing anchor stops the command with nothing on disk changed. The created and
//! deleted crate directories are staged with git because the checks read the tracked
//! state: without staging, `just ci` at the end of the command could not see the
//! new crate's `AGENTS.md` and would fail reading the deleted one.

mod edit;
mod template;

use crate::Outcome;
use crate::{process, workspace};
use std::path::Path;

const MODULES_DIR: &str = "crates/modules";
const MODULES_RS: &str = "crates/timbre/src/modules.rs";

pub(crate) fn new(id: &str) -> Outcome {
    validate(id)?;
    let root = workspace::root()?;
    let dir = format!("{MODULES_DIR}/{id}");
    if root.join(&dir).is_dir() {
        return Err(format!("{dir} already exists"));
    }
    let mut ids = module_ids_on_disk(&root)?;
    ids.push(id.to_owned());
    ids.sort();
    let root_manifest = edit::insert_root_dependency(
        &edit::set_members(&workspace::read(&root, edit::ROOT_MANIFEST)?, &ids)?,
        id,
    )?;
    let binary =
        edit::insert_binary_dependency(&workspace::read(&root, edit::BINARY_MANIFEST)?, id)?;
    let binary = edit::insert_feature(&binary, id, &ids)?;
    let modules = render_modules(&ids);

    write(
        &root,
        &format!("{dir}/Cargo.toml"),
        &template::cargo_toml(id),
    )?;
    write(&root, &format!("{dir}/AGENTS.md"), &template::agents(id))?;
    write(&root, &format!("{dir}/src/lib.rs"), &template::lib(id))?;
    write(
        &root,
        &format!("{dir}/src/log_events.rs"),
        &template::log_events(id),
    )?;
    write(
        &root,
        &format!("{dir}/src/failures.rs"),
        &template::failures(id),
    )?;
    write(&root, edit::ROOT_MANIFEST, &root_manifest)?;
    write(&root, edit::BINARY_MANIFEST, &binary)?;
    write(&root, MODULES_RS, &modules)?;
    process::run("git", &["add", "--", &dir], &root)?;
    refresh(&root)
}

pub(crate) fn remove(id: &str) -> Outcome {
    validate(id)?;
    let root = workspace::root()?;
    let dir = format!("{MODULES_DIR}/{id}");
    if !root.join(&dir).is_dir() {
        return Err(format!("{dir} is not a module directory"));
    }
    let ids: Vec<String> = module_ids_on_disk(&root)?
        .into_iter()
        .filter(|candidate| candidate != id)
        .collect();
    let root_manifest = edit::remove_root_dependency(
        &edit::set_members(&workspace::read(&root, edit::ROOT_MANIFEST)?, &ids)?,
        id,
    )?;
    let binary =
        edit::remove_binary_dependency(&workspace::read(&root, edit::BINARY_MANIFEST)?, id)?;
    let binary = edit::remove_feature(&binary, id, &ids)?;
    let modules = render_modules(&ids);

    std::fs::remove_dir_all(root.join(&dir))
        .map_err(|error| format!("cannot delete {dir}: {error}"))?;
    write(&root, edit::ROOT_MANIFEST, &root_manifest)?;
    write(&root, edit::BINARY_MANIFEST, &binary)?;
    write(&root, MODULES_RS, &modules)?;
    process::run(
        "git",
        &["rm", "-r", "--cached", "--ignore-unmatch", "--", &dir],
        &root,
    )?;
    refresh(&root)?;
    process::run("just", &["ci"], &root)
}

/// The generated `crates/timbre/src/modules.rs` for the sorted module ids. The text
/// must survive `cargo fmt` unchanged, so every attribute is written in rustfmt's own
/// multi-line form.
pub(crate) fn render_modules(ids: &[String]) -> String {
    let mut text = String::from(
        "//! The module list, generated by `cargo xtask module new|remove`; edit it through that command.\n\
         \n\
         use timbre_kernel::{Fallible, Registry};\n\
         \n\
         // With every module feature off the body never fails, yet the signature is the seam\n\
         // registration lines are generated into.\n",
    );
    let expect = "expect(\n    clippy::unnecessary_wraps,\n    reason = \"stable signature for generated registration\"\n)";
    if ids.is_empty() {
        text.push_str("#[");
        text.push_str(expect);
        text.push_str("]\n");
    } else {
        let features: Vec<String> = ids.iter().map(|id| format!("feature = \"{id}\"")).collect();
        let joined = features.join(", ");
        let not = if features.len() == 1 {
            format!("not({joined})")
        } else {
            format!("not(any({joined}))")
        };
        // Inside `cfg_attr` rustfmt indents the nested attribute one level deeper.
        let nested = expect.replace('\n', "\n    ");
        text.push_str("#[cfg_attr(\n    ");
        text.push_str(&not);
        text.push_str(",\n    ");
        text.push_str(&nested);
        text.push_str("\n)]\n");
    }
    text.push_str(
        "pub(crate) fn registry() -> Fallible<Registry> {\n    let registry = Registry::new();\n",
    );
    for id in ids {
        text.push_str("    #[cfg(feature = \"");
        text.push_str(id);
        text.push_str("\")]\n    let registry = registry.module(\"");
        text.push_str(id);
        text.push_str("\", timbre_");
        text.push_str(id);
        text.push_str("::register)?;\n");
    }
    text.push_str("    Ok(registry)\n}\n");
    text
}

fn refresh(root: &Path) -> Outcome {
    // `--workspace` re-resolves only the members, so a changed member set reaches
    // `Cargo.lock` without moving any external crate. `--offline` keeps the refresh from
    // fetching the registry index: the lock already pins every external crate, so a
    // failure here means the lock was already stale (a new external crate with no
    // vendored copy) and only a fetch can finish it.
    if let Err(error) = process::run("cargo", &["update", "--workspace", "--offline"], root) {
        return Err(format!(
            "Cargo.lock is stale for the new manifest: {error}\n\
             any `cargo` command without `--locked` (for example `cargo check`) will \
             fetch and finish the lock; re-run this command afterwards"
        ));
    }
    process::run("cargo", &["fmt", "--all"], root)
}

fn module_ids_on_disk(root: &Path) -> Outcome<Vec<String>> {
    let dir = root.join(MODULES_DIR);
    // A missing `crates/modules` is the state of a fresh clone after the last module
    // was removed (git does not keep empty directories): the empty list, not an error,
    // so `module new` can bootstrap from it.
    let Ok(entries) = std::fs::read_dir(&dir) else {
        return Ok(Vec::new());
    };
    let mut ids = Vec::new();
    for entry in entries {
        let entry = entry.map_err(|error| format!("cannot read {MODULES_DIR}: {error}"))?;
        if !entry.path().is_dir() {
            continue;
        }
        let name = entry.file_name();
        let Some(name) = name.to_str() else { continue };
        if entry.path().join("Cargo.toml").is_file() {
            ids.push(name.to_owned());
        }
    }
    ids.sort();
    Ok(ids)
}

fn validate(id: &str) -> Outcome {
    let shape_ok = !id.is_empty()
        && id
            .bytes()
            .next()
            .is_some_and(|byte| byte.is_ascii_lowercase())
        && id
            .bytes()
            .all(|byte| byte.is_ascii_lowercase() || byte.is_ascii_digit() || byte == b'_');
    if !shape_ok {
        return Err(format!("module id `{id}` must match [a-z][a-z0-9_]*"));
    }
    if matches!(id, "kernel" | "timbre" | "xtask") {
        return Err(format!("module id `{id}` is reserved"));
    }
    Ok(())
}

fn write(root: &Path, relative: &str, text: &str) -> Outcome {
    let path = root.join(relative);
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)
            .map_err(|error| format!("cannot create {}: {error}", parent.display()))?;
    }
    std::fs::write(&path, text).map_err(|error| format!("cannot write {relative}: {error}"))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn ids(values: &[&str]) -> Vec<String> {
        values.iter().map(|id| (*id).to_owned()).collect()
    }

    #[test]
    fn render_without_modules() {
        assert_eq!(
            render_modules(&ids(&[])),
            "//! The module list, generated by `cargo xtask module new|remove`; edit it through that command.\n\
             \n\
             use timbre_kernel::{Fallible, Registry};\n\
             \n\
             // With every module feature off the body never fails, yet the signature is the seam\n\
             // registration lines are generated into.\n\
             #[expect(\n\
            \x20   clippy::unnecessary_wraps,\n\
            \x20   reason = \"stable signature for generated registration\"\n\
             )]\n\
             pub(crate) fn registry() -> Fallible<Registry> {\n\
            \x20   let registry = Registry::new();\n\
            \x20   Ok(registry)\n\
             }\n"
        );
    }

    #[test]
    fn render_with_one_module() {
        assert_eq!(
            render_modules(&ids(&["hello"])),
            "//! The module list, generated by `cargo xtask module new|remove`; edit it through that command.\n\
             \n\
             use timbre_kernel::{Fallible, Registry};\n\
             \n\
             // With every module feature off the body never fails, yet the signature is the seam\n\
             // registration lines are generated into.\n\
             #[cfg_attr(\n\
            \x20   not(feature = \"hello\"),\n\
            \x20   expect(\n\
            \x20       clippy::unnecessary_wraps,\n\
            \x20       reason = \"stable signature for generated registration\"\n\
            \x20   )\n\
             )]\n\
             pub(crate) fn registry() -> Fallible<Registry> {\n\
            \x20   let registry = Registry::new();\n\
            \x20   #[cfg(feature = \"hello\")]\n\
            \x20   let registry = registry.module(\"hello\", timbre_hello::register)?;\n\
            \x20   Ok(registry)\n\
             }\n"
        );
    }

    #[test]
    fn render_with_two_modules() {
        assert_eq!(
            render_modules(&ids(&["a", "b"])),
            "//! The module list, generated by `cargo xtask module new|remove`; edit it through that command.\n\
             \n\
             use timbre_kernel::{Fallible, Registry};\n\
             \n\
             // With every module feature off the body never fails, yet the signature is the seam\n\
             // registration lines are generated into.\n\
             #[cfg_attr(\n\
            \x20   not(any(feature = \"a\", feature = \"b\")),\n\
            \x20   expect(\n\
            \x20       clippy::unnecessary_wraps,\n\
            \x20       reason = \"stable signature for generated registration\"\n\
            \x20   )\n\
             )]\n\
             pub(crate) fn registry() -> Fallible<Registry> {\n\
            \x20   let registry = Registry::new();\n\
            \x20   #[cfg(feature = \"a\")]\n\
            \x20   let registry = registry.module(\"a\", timbre_a::register)?;\n\
            \x20   #[cfg(feature = \"b\")]\n\
            \x20   let registry = registry.module(\"b\", timbre_b::register)?;\n\
            \x20   Ok(registry)\n\
             }\n"
        );
    }

    #[test]
    fn a_missing_modules_directory_yields_no_ids() {
        let root = std::env::temp_dir().join("timbre-xtask-module-ids-test");
        std::fs::create_dir_all(&root).expect("the temporary root exists");
        let absent = module_ids_on_disk(&root).expect("a missing crates/modules is empty");
        assert_eq!(absent, Vec::<String>::new());
        let one = root.join(MODULES_DIR).join("a");
        std::fs::create_dir_all(&one).expect("the temporary module directory exists");
        std::fs::write(one.join("Cargo.toml"), "[package]\n").expect("the manifest exists");
        assert_eq!(
            module_ids_on_disk(&root).expect("the directory is readable"),
            ids(&["a"])
        );
        std::fs::remove_dir_all(&root).expect("the temporary root is removed");
    }

    #[test]
    fn invalid_and_reserved_ids_are_rejected() {
        for bad in ["", "Hello", "9lives", "a-b", "kernel", "timbre", "xtask"] {
            assert!(validate(bad).is_err(), "`{bad}` must be rejected");
        }
        assert!(validate("a_b9").is_ok());
    }
}
